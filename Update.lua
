-- Load Saved Data
function loadData()
  lb.played = prefs.getInt("played", 0)
  lb.won = prefs.getInt("won", 0)
  lb.lost = prefs.getInt("lost", 0)
  lb.total_runs = prefs.getInt("total_runs", 0)
end

-- Save Data
function saveData()
  local editor = prefs.edit()
  editor.putInt("played", lb.played)
  editor.putInt("won", lb.won)
  editor.putInt("lost", lb.lost)
  editor.putInt("total_runs", lb.total_runs)
  editor.apply()
end

