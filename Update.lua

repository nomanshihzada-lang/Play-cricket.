-- 4. साउंड प्लेयर्स और वाइब्रेशन
local is_crowd_on = false 
local crowd_player = nil

local function toggleCrowd()
  if is_crowd_on then
    if crowd_player then
      crowd_player.stop()
      crowd_player.release()
      crowd_player = nil
    end
    is_crowd_on = false
    if service then service.speak("Crowd sound turned off.") end
  else
    pcall(function()
      crowd_player = MediaPlayer()
      crowd_player.setDataSource(audio_paths.en.crowd)
      crowd_player.setLooping(true)
      crowd_player.setVolume(0.3, 0.3)
      crowd_player.prepare()
      crowd_player.start()
      is_crowd_on = true
      if service then service.speak("Crowd sound turned on.") end
    end)
  end
end

local function playActionSound(action)
  local path = audio_paths[current_language][action]
  if path and path ~= "" then
    pcall(function()
      local player = MediaPlayer()
      player.setDataSource(path)
      player.prepare()
      player.start()
      player.setOnCompletionListener(MediaPlayer.OnCompletionListener{
        onCompletion = function(mp) mp.release() end
      })
    end)
  end
end

local function doVibrate(duration)
  if vibrator and vibrator.hasVibrator() then
    vibrator.vibrate(duration)
  end
end

