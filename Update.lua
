function showGame()
  score = 0 balls = 0 wickets = 0
  target = math.random(35, 75)
  match_stats = {dots = 0, ones = 0, twos = 0, threes = 0, fours = 0, sixes = 0}
  
  changeScreen(gameLayout)
  
  gameTargetText.setText("Target: " .. target)
  gameScoreText.setText("Score: 0/0")
  gameBallsText.setText("Balls: 0/30")
  gameStatusText.setText("English Commentary Started! Target is " .. target)
  
  if service then service.speak("Match Started! Target is " .. target .. " runs.") end
  
  local function updateGameUI(msg)
    gameScoreText.setText("Score: " .. score .. "/" .. wickets)
    gameBallsText.setText("Balls: " .. balls .. "/30")
    gameStatusText.setText(msg)
    if service then service.speak(msg .. " Score is " .. score) end
    
    if score >= target then
      lb.played = lb.played + 1 lb.won = lb.won + 1 lb.total_runs = lb.total_runs + score
      showPostMatch("You Won! Target Chased.")
    elseif wickets >= max_wickets or balls >= max_balls then
      lb.played = lb.played + 1 lb.lost = lb.lost + 1 lb.total_runs = lb.total_runs + score
      showPostMatch("Game Over! You Lost.")
    end
  end

  local function processBall(result)
    balls = balls + 1
    if result == "Wicket" then
      wickets = wickets + 1
      playActionSound(audio_paths.out)
      updateGameUI("Oh no! You are OUT!")
    else
      score = score + result
      if result == 6 then 
        match_stats.sixes = match_stats.sixes + 1
        playActionSound(audio_paths.six)
      elseif result == 4 then 
        match_stats.fours = match_stats.fours + 1
        playActionSound(audio_paths.four) 
      elseif result == 3 then 
        match_stats.threes = match_stats.threes + 1
        playActionSound(audio_paths.three)
      elseif result == 2 then 
        match_stats.twos = match_stats.twos + 1
        playActionSound(audio_paths.two)
      elseif result == 1 then 
        match_stats.ones = match_stats.ones + 1
        playActionSound(audio_paths.one)
      elseif result == 0 then 
        match_stats.dots = match_stats.dots + 1 
        playActionSound(audio_paths.dot)
      end
      updateGameUI("You scored " .. result .. " runs.")
    end
  end

  btnA.onClick = function()
    local outcomes = {6, 4, "Wicket"}
    processBall(outcomes[math.random(1, #outcomes)])
  end

  btnX.onClick = function() processBall(0) end

  btnC.onClick = function()
    local outcomes = {1, 2, 3, 4, "Wicket"}
    processBall(outcomes[math.random(1, #outcomes)])
  end
  
  btnGameBack.onClick = function() showMainMenu() end
end

